// 안전 질문 차단. 설비를 직접 조작하는 방법·허락이나 비상 대응을 묻는 질문은 LLM을 부르지 않고 고정 문장으로 돌려보낸다.
// 단어 하나("정지", "열어", "점검")만으로 막으면 "고로가 정지하면 어떻게 되나요?" 같은 교육 질문까지 막히므로,
// 조작 지시를 구하는 표현만 막는다. 공백을 지우고 비교한다.

/** 손으로 조작하는 장치. */
const CONTROLS = ["밸브", "스위치", "버튼", "레버", "차단기", "핸들", "콕"];
/** 조작 동작(어간). */
// "열" 한 글자는 열풍로·가열로에도 있어서 활용형으로 쓴다.
const ACTIONS = ["열어", "열면", "열고", "여는", "닫", "누르", "눌러", "돌려", "돌리", "켜", "끄", "꺼", "올려", "내려", "조작", "작동", "멈추", "멈춰"];

const RULES: RegExp[] = [
  // 비상 대응: "비상 정지 버튼", "비상시 어떻게", "비상 상황에"
  /비상(정지|시|상황|때|대응|버튼|조치)/,
  // 설비를 움직이게·멈추게 하는 방법이나 허락을 구함: "고로를 정지시키는 방법", "설비를 조작해도 돼요?"
  // "작동되나요?"(원리 질문)는 막지 않도록 허락을 구하는 "~해도/시켜도"만 본다.
  /(정지|가동|작동|조작|멈추|멈춰)(시켜|해|하여)?도(돼|되|될|괜찮)/,
  /(정지|가동|작동|조작|멈추)(시키|하)(는|기|려면|할)?(법|방법|순서|절차)/,
];

export const SAFETY_ANSWER = "현장 안전 작업표준과 담당자에게 확인하세요.";

export function isSafetyQuestion(question: string): boolean {
  const q = question.replace(/\s/g, "");
  // 조작 장치 + 조작 동작이 함께 있으면 조작 방법을 묻는 것으로 본다("밸브를 열어도 돼요?", "스위치 눌러도 되나요?").
  if (CONTROLS.some((c) => q.includes(c)) && ACTIONS.some((a) => q.includes(a))) return true;
  return RULES.some((rule) => rule.test(q));
}
